// Local artifact preparation only. Network publication belongs to the protected workflow.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';

export const base = 'https://github.com/Leovikii/mpvkit/releases/download/';
export const digest = bytes => createHash('sha256').update(bytes).digest('hex');
export function parseVersion(value) {
  const match = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-(alpha|beta|rc)\.(0|[1-9]\d*))?$/.exec(value);
  assert(match, `Unsupported release version: ${value}`);
  return { numbers: match.slice(1, 4).map(Number), pre: match[4], sequence: Number(match[5] || 0) };
}
export function compare(a, b) {
  const x = parseVersion(a), y = parseVersion(b);
  for (let i = 0; i < 3; i++) if (x.numbers[i] !== y.numbers[i]) return Math.sign(x.numbers[i] - y.numbers[i]);
  const rank = { alpha: 0, beta: 1, rc: 2, undefined: 3 };
  return Math.sign(rank[x.pre] - rank[y.pre] || x.sequence - y.sequence);
}
export function archVersion(version) { parseVersion(version); return version.replace(/-(alpha|beta|rc)\./, '$1'); }
export function recipe(version, sha256) {
  assert(/^[a-f0-9]{64}$/.test(sha256), 'Archive SHA-256 required');
  return `# Generated by scripts/release.mjs; review before publishing to AUR.
pkgname=mpvkit-bin
pkgver=${archVersion(version)}
pkgrel=1
pkgdesc='MPV installation and configuration manager${parseVersion(version).pre ? " (preview)" : ""}'
arch=('x86_64')
url='https://github.com/Leovikii/mpvkit'
license=('GPL-3.0-or-later')
depends=('webkit2gtk-4.1' 'gtk3' 'xdg-utils')
optdepends=('mpv: playback core' 'polkit: authorize MPV package operations')
provides=('mpvkit')
conflicts=('mpvkit' 'mpvkit-preview-bin')
options=('!strip' '!debug')
source=("mpvkit-${version}-linux-x86_64.tar.zst::${base}v${version}/mpvkit-${version}-linux-x86_64.tar.zst")
sha256sums=('${sha256}')
package() {
  cp -a "$srcdir/usr" "$pkgdir/"
}
`;
}
export function promote(index, release) {
  assert(index.schemaVersion === 1, 'Unsupported channel schema');
  for (const key of ['stable', 'preview']) {
    const entry = index[key];
    if (entry) {
      parseVersion(entry.version);
      assert(entry.manifest === `${base}v${entry.version}/updater.json`, 'Invalid existing channel URL');
      assert(key !== 'stable' || !parseVersion(entry.version).pre, 'Stable channel contains prerelease');
    }
  }
  const key = parseVersion(release.version).pre ? 'preview' : 'stable';
  assert(release.manifest === `${base}v${release.version}/updater.json`, 'Invalid new channel URL');
  assert(release.archPackage === null || ['mpvkit-bin', 'mpvkit-preview-bin'].includes(release.archPackage), 'Invalid AUR package');
  assert(!index[key] || compare(release.version, index[key].version) >= 0, 'Channel downgrade rejected');
  return { ...index, [key]: release };
}
function json(file) { return JSON.parse(fs.readFileSync(file, 'utf8')); }
function writeJson(file, value) { fs.writeFileSync(file, JSON.stringify(value, null, 2) + '\n'); }
function run(program, args, options = {}) { execFileSync(program, args, { stdio: 'inherit', ...options }); }
export function versionCheck(tag) {
  const version = json('package.json').version;
  parseVersion(version);
  assert(json('src-tauri/tauri.conf.json').version === version);
  assert(fs.readFileSync('src-tauri/Cargo.toml', 'utf8').includes(`version = "${version}"`));
  if (tag) assert(tag === `v${version}`, 'Tag and source version differ');
  return version;
}
export function stageArch(out, executable = 'src-tauri/target/release/mpvkit') {
  const version = versionCheck();
  assert(!fs.existsSync(path.join(out, 'stage')), 'Use a fresh staging directory');
  const copy = (source, dest) => {
    const target = path.join(out, 'stage', dest);
    fs.mkdirSync(path.dirname(target), { recursive: true }); fs.copyFileSync(source, target);
  };
  copy(executable, 'usr/bin/mpvkit'); fs.chmodSync(path.join(out, 'stage/usr/bin/mpvkit'), 0o755);
  copy('packaging/io.github.mpvkit.desktop', 'usr/share/applications/io.github.mpvkit.desktop');
  copy('src-tauri/icons/icon.png', 'usr/share/icons/hicolor/256x256/apps/io.github.mpvkit.png');
  copy('LICENSE', 'usr/share/licenses/mpvkit/LICENSE');
  // tauri-utils resource_dir: /usr/bin/../lib/<Cargo package name>.
  const resources = json('src-tauri/tauri.conf.json').bundle.resources;
  for (let [source, dest] of Object.entries(resources)) {
    if (source.includes('webview2-sdk')) continue;
    if (/app-(dependency|distribution)/.test(source)) source = source.replace(/\.(txt|json)$/, '-linux.$1');
    copy(path.join('src-tauri', source), `usr/lib/mpvkit/${dest}`);
  }
  return { version, stage: path.join(out, 'stage') };
}
export function manifest(out, version, date, notes) {
  parseVersion(version); assert(!Number.isNaN(Date.parse(date)), 'Valid publication date required');
  const files = fs.readdirSync(out).filter(f => fs.statSync(path.join(out, f)).isFile());
  const installers = files.filter(f => f.endsWith('-setup.exe'));
  assert(installers.length === 1, 'Exactly one Windows installer required');
  const installer = installers[0];
  assert(files.includes(installer + '.sig'), 'Installer signature required');
  assert(files.includes(`mpvkit-${version}-linux-x86_64.tar.zst`), 'Arch archive required');
  assert(files.some(f => f.endsWith('.pkg.tar.zst')), 'Arch package required');
  const signature = fs.readFileSync(path.join(out, installer + '.sig'), 'utf8').trim();
  assert(signature.length > 0 && signature.length <= 4096);
  const value = { version, notes, pub_date: date, platforms: { 'windows-x86_64': { url: `${base}v${version}/${installer}`, signature } } };
  writeJson(path.join(out, 'updater.json'), value);
  return value;
}
function main([command, out = '.local/release', extra]) {
  const version = versionCheck(command === 'check' ? out : undefined);
  if (command === 'check') return;
  if (command === 'arch') {
    assert(process.platform === 'linux', 'Arch packaging requires Linux');
    const { stage } = stageArch(out);
    const archive = `mpvkit-${version}-linux-x86_64.tar.zst`;
    run('tar', ['--zstd', '-cf', path.resolve(out, archive), '-C', stage, 'usr']);
    const aur = path.join(out, 'aur'); fs.mkdirSync(aur);
    fs.copyFileSync(path.join(out, archive), path.join(aur, archive));
    fs.writeFileSync(path.join(aur, 'PKGBUILD'), recipe(version, digest(fs.readFileSync(path.join(out, archive)))));
    fs.writeFileSync(path.join(aur, '.SRCINFO'), execFileSync('makepkg', ['--printsrcinfo'], { cwd: aur }));
    // makepkg validates the fixed archive checksum; it does not compile the application again.
    run('makepkg', ['--nodeps', '--noconfirm'], { cwd: aur });
    for (const f of fs.readdirSync(aur).filter(f => f.endsWith('.pkg.tar.zst'))) fs.copyFileSync(path.join(aur, f), path.join(out, f));
  } else if (command === 'manifest') {
    manifest(out, version, new Date().toISOString(), fs.readFileSync(`docs/v${version}/notes.md`, 'utf8'));
    const lines = fs.readdirSync(out).filter(f => fs.statSync(path.join(out, f)).isFile() && f !== 'SHA256SUMS').sort()
      .map(f => `${digest(fs.readFileSync(path.join(out, f)))}  ${f}`);
    fs.writeFileSync(path.join(out, 'SHA256SUMS'), lines.join('\n') + '\n');
  } else if (command === 'promote') {
    assert(fs.existsSync(out), 'Existing channels.json is required (initialize it explicitly for first release)');
    writeJson(out, promote(json(out), { version, manifest: `${base}v${version}/updater.json`, archPackage: extra === 'none' ? null : extra }));
  } else throw new Error('Usage: release.mjs check <tag> | arch <out> | manifest <out> | promote <channels.json> <none|mpvkit-bin|mpvkit-preview-bin>');
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) main(process.argv.slice(2));
