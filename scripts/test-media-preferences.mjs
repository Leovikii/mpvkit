import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'mpvkit-v015-tracks-'));
const ffmpeg=process.env.MPVKIT_FFMPEG,mpv=process.env.MPVKIT_REAL_MPV;
assert(ffmpeg&&mpv,'Set MPVKIT_FFMPEG and MPVKIT_REAL_MPV');
const hash=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
assert.equal(hash(ffmpeg),'7491af2d1d44f695d7c169db5f12b51d61667d585619dea75d3a0fc96215a5f1');
const playerRoot=path.dirname(mpv),config=path.join(playerRoot,'portable_config');
const manifest=JSON.parse(fs.readFileSync(path.join(playerRoot,'.mpvkit/install.json')));
assert.equal(hash(mpv),manifest.files.find(f=>f.path==='mpv.exe').sha256);
const conf=fs.readFileSync(path.join(config,'mpv.conf'),'utf8');
const defaults=conf.match(/^alang=(.+)$/m)[1].split(',');assert.equal(conf.match(/^slang=(.+)$/m)[1],defaults.join(','));
const rank=tag=>/^(zh|cmn|yue|chs|cht|chi|zho)/i.test(tag)?0:/^(ja|jpn)/i.test(tag)?1:/^(en|eng)/i.test(tag)?2:3;
function run(exe,args){const r=spawnSync(exe,args,{encoding:'utf8',windowsHide:true,timeout:30000});assert.ifError(r.error);assert.equal(r.status,0,r.stderr+r.stdout);return r.stdout;}
const subtitle=path.join(root,'sample.srt');fs.writeFileSync(subtitle,'1\n00:00:00,000 --> 00:00:02,000\nSynthetic subtitle\n');
const source=path.join(root,'source.mkv');
run(ffmpeg,['-v','error','-f','lavfi','-i','color=black:s=128x72:r=1:d=1','-f','lavfi','-i','anullsrc=r=8000:cl=mono','-i',subtitle,'-map','0:v','-map','1:a','-map','2:s','-t','1','-c:v','libx264','-preset','ultrafast','-c:a','pcm_s16le','-c:s','srt',source]);
const probe=path.join(root,'probe.lua');fs.writeFileSync(probe,"local mp=require 'mp';local u=require 'mp.utils';mp.register_event('file-loaded',function() mp.add_timeout(0.05,function() print('TRACK_RESULT='..u.format_json(mp.get_property_native('track-list')));mp.commandv('quit') end) end)");
const cases=[...new Set([...defaults,'chi','zho','ZH-HANS','CHI','jpn','JPN','eng','ENG','spa'])].map(tag=>({id:tag,tags:[...['es','en','ja'].filter(t=>rank(t)>rank(tag)),tag]}));
cases.push({id:'manual',tags:['eng','zho'],args:['--aid=1','--sid=1'],expected:1});
cases.push({id:'missing-tags',tags:['und','und'],expected:1,defaultFirst:true});
cases.push({id:'default-vs-language',tags:['eng','zh-Hans'],defaultFirst:true});
cases.push({id:'forced-matching',tags:['eng','zho'],defaultFirst:true,forcedLast:true});
cases.push({id:'external-subtitle',tags:['eng','zho'],external:true});
const evidence=[];
for(const [index,c] of cases.entries()){
 const media=path.join(root,index+'-'+c.id+'.mkv');const args=['-v','error','-i',source,'-map','0:v'];
 for(const [i,lang] of c.tags.entries())args.push('-map','0:a','-map','0:s','-metadata:s:a:'+i,'language='+lang,'-metadata:s:s:'+i,'language='+lang,'-disposition:a:'+i,c.defaultFirst&&i===0?'default':'0','-disposition:s:'+i,c.forcedLast&&i===c.tags.length-1?'forced':c.defaultFirst&&i===0?'default':'0');
 args.push('-c','copy',media);run(ffmpeg,args);
 const stdout=run(mpv,['--config-dir='+config,'--load-scripts=no','--ao=null','--vo=null','--terminal=yes','--sub-auto=no','--script='+probe,...(c.args||[]),...(c.external?['--sub-file='+subtitle]:[]),'--',media]);
 const tracks=JSON.parse(stdout.match(/TRACK_RESULT=(.*)/)[1]);fs.writeFileSync(path.join(root,index+'-'+c.id+'.json'),JSON.stringify(tracks));
 const selected=type=>tracks.find(t=>t.type===type&&t.selected);const expected=c.expected??c.tags.length;
 assert.equal(selected('audio')?.id,expected,c.id+' audio');
 if(c.external)assert.equal(selected('sub')?.external,true,c.id);else assert.equal(selected('sub')?.id,expected,c.id+' subtitle');
 evidence.push({id:c.id,audio:selected('audio'),subtitle:selected('sub')});
}
fs.writeFileSync(path.join(root,'result.json'),JSON.stringify({passed:true,evidence},null,2));
console.log(cases.length+' real MPV track cases passed: '+root);
