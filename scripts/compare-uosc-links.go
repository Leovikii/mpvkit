// 仅核对固定第三方 uosc helper 的 Go 元数据，不执行两个输入程序。
package main

import (
	"bytes"
	"crypto/sha256"
	"debug/gosym"
	"debug/pe"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"reflect"
	"sort"
	"strings"
)

type identity struct {
	Size   int64  `json:"size"`
	SHA256 string `json:"sha256"`
}
type module struct {
	Module  string `json:"module"`
	Version string `json:"version"`
}
type function struct {
	Name   string `json:"name"`
	Offset uint64 `json:"offset"`
	Size   uint64 `json:"size"`
}
type sourcePath struct {
	Kind string `json:"kind"`
	Path string `json:"path"`
}
type section struct {
	Name     string   `json:"name"`
	Identity identity `json:"identity"`
}
type inspection struct {
	Identity               identity       `json:"identity"`
	FunctionCount          int            `json:"functionCount"`
	FunctionMetadataSHA256 string         `json:"functionMetadataSha256"`
	SourcePathCount        int            `json:"sourcePathCount"`
	SourcePathsSHA256      string         `json:"normalizedSourcePathsSha256"`
	SourceKinds            map[string]int `json:"sourceKinds"`
	Sections               []section      `json:"sections"`
	functions              []function
	paths                  []sourcePath
}

func readJSON(file string, value any) error {
	data, err := os.ReadFile(file)
	if err != nil {
		return err
	}
	return json.Unmarshal(data, value)
}
func dataIdentity(data []byte) identity {
	digest := sha256.Sum256(data)
	return identity{int64(len(data)), hex.EncodeToString(digest[:])}
}
func verifyIdentity(file string, expected identity) error {
	if expected.Size <= 0 || expected.Size > 16*1024*1024 {
		return fmt.Errorf("文件大小不在固定核对范围")
	}
	info, err := os.Stat(file)
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() || info.Size() != expected.Size {
		return fmt.Errorf("文件类型/大小不同")
	}
	data, err := os.ReadFile(file)
	if err != nil {
		return err
	}
	if dataIdentity(data) != expected {
		return fmt.Errorf("文件摘要不同")
	}
	return nil
}
func jsonDigest(value any) string {
	data, err := json.Marshal(value)
	if err != nil {
		panic(err)
	}
	return dataIdentity(data).SHA256
}
func normalizePath(path string, modules []module) (sourcePath, error) {
	path = strings.ReplaceAll(path, "\\", "/")
	if path == "<autogenerated>" {
		return sourcePath{"generated", path}, nil
	}
	if _, tail, ok := strings.Cut(path, "/src/ziggy/"); ok {
		return sourcePath{"uosc", "src/ziggy/" + tail}, nil
	}
	for _, marker := range []string{"/Go/src/", "/sdk/go/src/"} {
		if _, tail, ok := strings.Cut(path, marker); ok {
			return sourcePath{"standard", "go/src/" + tail}, nil
		}
	}
	for _, mod := range modules {
		prefix := mod.Module + "@" + mod.Version + "/"
		if _, tail, ok := strings.Cut(path, "/"+prefix); ok {
			return sourcePath{"module", prefix + tail}, nil
		}
	}
	return sourcePath{}, fmt.Errorf("无法归入固定源码的路径")
}
func inspect(file string, expected identity, modules []module, selected map[sourcePath]bool) (result inspection, err error) {
	// debug/gosym 的旧格式解析内部可panic；受限入口将其转换成拒绝结果。
	defer func() {
		if value := recover(); value != nil {
			err = fmt.Errorf("Go表解析失败：%v", value)
		}
	}()
	if err = verifyIdentity(file, expected); err != nil {
		return result, err
	}
	binary, err := pe.Open(file)
	if err != nil {
		return result, err
	}
	defer binary.Close()
	header, ok := binary.OptionalHeader.(*pe.OptionalHeader64)
	if !ok || binary.Machine != pe.IMAGE_FILE_MACHINE_AMD64 {
		return result, fmt.Errorf("不是Windows amd64 PE64")
	}
	text, rdata := binary.Section(".text"), binary.Section(".rdata")
	if text == nil || rdata == nil {
		return result, fmt.Errorf("缺少固定Go节")
	}
	for _, sec := range binary.Sections {
		if uint64(sec.Offset)+uint64(sec.Size) > uint64(expected.Size) {
			return result, fmt.Errorf("节越过文件边界")
		}
		raw, readErr := sec.Data()
		if readErr != nil {
			return result, readErr
		}
		result.Sections = append(result.Sections, section{sec.Name, dataIdentity(raw)})
	}
	raw, err := rdata.Data()
	if err != nil {
		return result, err
	}
	magic := []byte{0xf1, 0xff, 0xff, 0xff, 0, 0, 1, 8}
	offset := bytes.Index(raw, magic)
	if offset < 0 || bytes.Index(raw[offset+len(magic):], magic) >= 0 {
		return result, fmt.Errorf("Go1.20+ amd64表头缺失或不唯一")
	}
	start := header.ImageBase + uint64(text.VirtualAddress)
	table, err := gosym.NewTable(nil, gosym.NewLineTable(raw[offset:], start))
	if err != nil {
		return result, err
	}
	if len(table.Funcs) == 0 || len(table.Files) == 0 {
		return result, fmt.Errorf("Go表为空")
	}
	for _, fun := range table.Funcs {
		if fun.Entry < start || fun.End < fun.Entry || fun.End-start > uint64(text.Size) {
			return result, fmt.Errorf("函数越过代码节")
		}
		result.functions = append(result.functions, function{fun.Name, fun.Entry - start, fun.End - fun.Entry})
	}
	result.SourceKinds = make(map[string]int)
	for path := range table.Files {
		normalized, normalizeErr := normalizePath(path, modules)
		if normalizeErr != nil {
			return result, normalizeErr
		}
		if normalized.Kind != "generated" && !selected[normalized] {
			return result, fmt.Errorf("运行时表引用不在已验证源码选择中：%s", normalized.Path)
		}
		result.paths = append(result.paths, normalized)
		result.SourceKinds[normalized.Kind]++
	}
	sort.Slice(result.paths, func(i, j int) bool {
		if result.paths[i].Kind != result.paths[j].Kind {
			return result.paths[i].Kind < result.paths[j].Kind
		}
		return result.paths[i].Path < result.paths[j].Path
	})
	result.Identity = expected
	result.FunctionCount, result.SourcePathCount = len(result.functions), len(result.paths)
	result.FunctionMetadataSHA256, result.SourcePathsSHA256 = jsonDigest(result.functions), jsonDigest(result.paths)
	return result, nil
}
func run(args []string) error {
	if len(args) != 4 {
		return fmt.Errorf("需要固定上游exe、重建exe、report.json与selected-files.json四个本地路径")
	}
	var materials struct {
		Helper struct {
			identity
			Dependencies []module `json:"dependencies"`
		} `json:"uoscHelper"`
	}
	if err := readJSON("resources/source-materials.json", &materials); err != nil {
		return err
	}
	var rebuild struct {
		Mode            string   `json:"verificationMode"`
		SourceManifest  string   `json:"sourceManifestSha256"`
		SourcesVerified bool     `json:"selectedSourcesVerified"`
		Upstream        identity `json:"upstream"`
		Rebuilt         identity `json:"rebuilt"`
		Selected        identity `json:"selectedFileReport"`
	}
	if err := readJSON(args[2], &rebuild); err != nil {
		return err
	}
	manifest, err := os.ReadFile("docs/v0.1.0/evidence/2026-10-20-uosc-source-archives.json")
	if err != nil {
		return err
	}
	if rebuild.Mode != "fixed-uosc-offline-windows-rebuild" || !rebuild.SourcesVerified || rebuild.Upstream != materials.Helper.identity || rebuild.SourceManifest != dataIdentity(manifest).SHA256 {
		return fmt.Errorf("重建报告身份或源码清单已过期")
	}
	if err := verifyIdentity(args[3], rebuild.Selected); err != nil {
		return err
	}
	var selection struct {
		Files []sourcePath `json:"files"`
	}
	if err := readJSON(args[3], &selection); err != nil {
		return err
	}
	selected := make(map[sourcePath]bool)
	for _, file := range selection.Files {
		if selected[file] {
			return fmt.Errorf("选中文件重复")
		}
		selected[file] = true
	}
	if len(selected) == 0 {
		return fmt.Errorf("选中文件为空")
	}
	upstream, err := inspect(args[0], rebuild.Upstream, materials.Helper.Dependencies, selected)
	if err != nil {
		return err
	}
	rebuilt, err := inspect(args[1], rebuild.Rebuilt, materials.Helper.Dependencies, selected)
	if err != nil {
		return err
	}
	report := struct {
		Mode                      string     `json:"verificationMode"`
		Upstream                  inspection `json:"upstream"`
		Rebuilt                   inspection `json:"rebuilt"`
		FunctionMetadataEqual     bool       `json:"functionMetadataEqual"`
		SourcePathsEqual          bool       `json:"normalizedSourcePathsEqual"`
		SourceReferencesVerified  bool       `json:"runtimeSourceReferencesMatchVerifiedSelection"`
		ByteIdentical             bool       `json:"byteIdentical"`
		SemanticEquivalenceProven bool       `json:"semanticEquivalenceProven"`
		CompleteReview            bool       `json:"completeDistributionReview"`
	}{"fixed-uosc-read-only-go-runtime-metadata", upstream, rebuilt,
		reflect.DeepEqual(upstream.functions, rebuilt.functions), reflect.DeepEqual(upstream.paths, rebuilt.paths), true,
		upstream.Identity == rebuilt.Identity, false, false}
	encoder := json.NewEncoder(os.Stdout)
	encoder.SetIndent("", "  ")
	return encoder.Encode(report)
}
func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
