// Local preview checks only; no Tauri, real player, registry or downloads.
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { pathToFileURL, fileURLToPath } from 'node:url';
import path from 'node:path';
const output = fileURLToPath(new URL('../../../.local/ui-v015/', import.meta.url));
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const errors = [];
const requests = [];
try {
  const page = await browser.newPage({ viewport: { width: 1120, height: 820 }, reducedMotion: 'reduce' });
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/^https?:/.test(request.url())) requests.push(request.url()); });
  await page.goto(pathToFileURL(path.join(output, 'preview.html')).href);
  const screenshot = async name => { await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))); return page.screenshot({ path: path.join(output, `${name}.png`), animations: 'disabled' }); };
  const scenario = value => page.getByLabel('预览场景 / Scenario').selectOption(value);
  const nav = name => page.getByRole('button', { name, exact: true });
  const noOverflow = async () => assert.equal(await page.evaluate(() => [...document.querySelectorAll('.page-surface, .page-content, .preview-tools')].every(x => x.scrollWidth <= x.clientWidth + 1)), true);
  await page.getByRole('heading', { name: '播放器', exact: true }).waitFor();
  assert.equal(await nav('打开媒体文件').count(), 0);
  assert.equal(await nav('打开文件夹').isVisible(), false);
  await page.getByRole('button', { name: /^高级选项/ }).click();
  await nav('打开文件夹').waitFor({ state: 'visible' });
  await page.getByRole('button', { name: /^高级选项/ }).click();
  await screenshot('management-light');
  await nav('深色').click();
  await screenshot('management-dark');
  await nav('浅色').click();
  await scenario('fresh');
  assert.equal(await nav('播放设置').count(), 0);
  await screenshot('fresh');
  await nav('安装播放器').click();
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.activeElement?.textContent === '安装播放器');
  await nav('安装播放器').click();
  await page.getByRole('dialog').getByRole('button', { name: '安装', exact: true }).click();
  await nav('生成配置').click();
  await page.getByLabel('画质', { exact: true }).waitFor({ state: 'visible' });
  await page.getByLabel('HDR 输出', { exact: true }).waitFor({ state: 'visible' });
  assert.equal(await nav('打开配置文件夹').isVisible(), false);
  assert.equal(await nav('播放快捷键').count(), 0);
  await page.getByRole('button', { name: /^高级选项/ }).click();
  await nav('打开配置文件夹').waitFor({ state: 'visible' });
  assert.equal(await nav('重新检测').count(), 0);
  assert.equal(await page.getByLabel('画质', { exact: true }).inputValue(), 'balanced');
  for (const [value, hint] of [['efficient', '降低渲染负担，适合低性能设备。'], ['balanced', '推荐日常使用，兼顾画质与性能。'], ['quality', '推荐独立显卡使用，卡顿时请降低档位。']]) {
    await page.getByLabel('画质', { exact: true }).selectOption(value);
    assert.equal(await page.getByText(hint, { exact: true }).count(), 1);
  }
  assert.equal(await page.getByLabel('HDR 输出', { exact: true }).inputValue(), 'auto');
  for (const mode of ['on', 'off', 'auto']) {
    await page.getByLabel('HDR 输出', { exact: true }).selectOption(mode);
    assert.equal(await page.getByLabel('HDR 输出', { exact: true }).inputValue(), mode);
  }
  assert.equal(await page.getByLabel('优先音轨', { exact: true }).count(), 0);
  assert.equal(await page.getByLabel('优先字幕', { exact: true }).count(), 0);
  await page.getByLabel('画质', { exact: true }).selectOption('quality');
  await nav('播放器').click();
  await nav('播放设置').click();
  await page.getByRole('button', { name: /^高级选项/ }).click();
  assert.equal(await page.getByLabel('画质', { exact: true }).inputValue(), 'quality');
  await screenshot('configuration');
  await nav('安装配置').click();
  await page.getByRole('dialog').waitFor();
  await screenshot('confirmation');
  await page.getByRole('dialog').getByRole('button', { name: '安装', exact: true }).click();
  await scenario('conflict');
  await nav('播放设置').click();
  await nav('保存更改').click();
  const dialog = page.getByRole('dialog');
  assert.equal(await dialog.getByRole('button', { name: '保存', exact: true }).isDisabled(), true);
  await dialog.getByRole('checkbox').check();
  assert.equal(await dialog.getByRole('button', { name: '保存', exact: true }).isEnabled(), true);
  for (let i = 0; i < 12; i++) { await page.keyboard.press('Tab'); assert.equal(await dialog.evaluate(x => x.contains(document.activeElement)), true); }
  await screenshot('conflict');
  await page.keyboard.press('Escape');
  await scenario('broken');
  assert.equal(await nav('播放设置').count(), 0);
  await screenshot('broken');
  await scenario('failed');
  await nav('重试登记').click();
  await dialog.getByRole('button', { name: '保存', exact: true }).click();
  assert.equal(await page.getByText('登记失败', { exact: true }).count(), 0);
  await nav('应用设置').click();
  await screenshot('settings');
  await nav('English').click();
  for (const size of [{width:1200,height:800},{width:900,height:700},{width:640,height:600}]) {
    await page.setViewportSize(size);
    for (const title of ['Player', 'Playback', 'App settings']) { await nav(title).click(); await noOverflow(); }
  }
  await screenshot('settings-narrow-en');
  await nav('Dark').focus();
  await page.keyboard.press('Tab');
  await page.getByRole('tooltip', { name: 'Player', exact: true }).waitFor();
  await page.keyboard.press('Enter');
  await page.getByRole('heading', { name: 'Player', exact: true, level: 1 }).waitFor();
  await page.setViewportSize({width:1200,height:800});
  await page.evaluate(() => document.documentElement.style.fontSize = '200%');
  await nav('App settings').click();
  await noOverflow();
  await screenshot('settings-text-200');
  assert.equal(await page.locator('.page-surface').evaluate(x => x.getBoundingClientRect().bottom <= innerHeight), true);
  assert.equal(await page.locator('.page-content').evaluate(x => getComputedStyle(x).transitionDuration), '0s');
  const motionPage = await browser.newPage({ viewport: { width: 1120, height: 820 }, reducedMotion: 'no-preference' });
  motionPage.on('pageerror', error => errors.push(error.message));
  await motionPage.goto(pathToFileURL(path.join(output, 'preview.html')).href);
  await motionPage.getByRole('button', { name: '播放设置', exact: true }).click();
  await motionPage.waitForFunction(() => document.querySelector('.page-content')?.style.transitionDuration === '200ms');
  await motionPage.waitForFunction(() => { const x = document.querySelector('.page-content'); return x && getComputedStyle(x).opacity === '1' && new DOMMatrixReadOnly(getComputedStyle(x).transform).m42 === 0; });
  await motionPage.locator('.page-content').evaluate(x => x.dataset.samePage = 'kept');
  await motionPage.getByRole('button', { name: '播放设置', exact: true }).click();
  assert.equal(await motionPage.locator('.page-content').getAttribute('data-same-page'), 'kept');
  for (const name of ['应用设置', '播放器', '播放设置', '应用设置']) await motionPage.getByRole('button', { name, exact: true }).click();
  await motionPage.getByRole('heading', { name: '应用设置', exact: true }).waitFor();
  assert.equal(await motionPage.locator('.page-content').count(), 1);
  await motionPage.emulateMedia({ reducedMotion: 'reduce' });
  await motionPage.getByRole('button', { name: '播放器', exact: true }).click();
  await motionPage.getByRole('heading', { name: '播放器', exact: true, level: 1 }).waitFor();
  assert.equal(await motionPage.locator('.page-content').evaluate(x => getComputedStyle(x).transitionDuration), '0s');
  await motionPage.close();
  assert.deepEqual(errors, []);
  assert.deepEqual(requests, []);
  console.log('PASS: scenarios, navigation, retained draft, conflict blocking, dialog focus/Esc/return, keyboard tooltip, layouts, 200% text, fade-up, rapid/same-page navigation, reduced motion, no runtime errors or network requests.');
} finally { await browser.close(); }
